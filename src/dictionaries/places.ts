/**
 * Returns the cities of a country, or all cities when the country has none.
 * @param country - The ISO 3166 country code
 */
export const citiesIn = (country: string): readonly ECity[] => {
  const result = cities.filter((city) => city.country === country);
  return result.length > 0 ? result : cities;
};

// .............................................................................
/**
 * Returns the city with a name, or throws when the dictionary has none.
 * @param name - The name of the city
 */
export const cityNamed = (name: string): ECity => {
  const city = cities.find((entry) => entry.name === name);
  if (!city) {
    throw new Error(`places: unknown city "${name}"`);
  }
  return city;
};
