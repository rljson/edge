/** The body types of the vehicles */
export type EBodyType =
  | 'sedan'
  | 'hatchback'
  | 'wagon'
  | 'suv'
  | 'coupe'
  | 'convertible'
  | 'van'
  | 'pickup'
  | 'truck'
  | 'sportscar'
  | 'minivan'
  | 'microcar';

// #############################################################################
/** The fuels of the vehicles */
export type EFuel = 'petrol' | 'diesel' | 'hybrid' | 'electric' | 'hydrogen';

// #############################################################################
/** A vehicle model of a brand */
export interface EVehicleModel {
  /** The brand, as in the manufacturers dictionary */
  brand: string;

  /** The name of the model */
  model: string;

  /** The body type of the model */
  bodyType: EBodyType;

  /** The fuel of the model */
  fuel: EFuel;
}

// .............................................................................
/**
 * Shortens the model entries of one brand.
 * @param brand - The brand of the models
 * @param list - Model name, body type and fuel per model
 */
const models = (
  brand: string,
  list: readonly (readonly [string, EBodyType, EFuel])[],
): EVehicleModel[] =>
  list.map(([model, bodyType, fuel]) => ({ brand, model, bodyType, fuel }));

